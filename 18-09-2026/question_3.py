sub1, sub2, sub3, sub4, sub5 = subjects
print("Tuple of subjects:", subjects)
print("Subject 1:", sub1)
print("Subject 2:", sub2)
print("Subject 3:", sub3)
print("Subject 4:", sub4)
print("Subject 5:", sub5)
